import { expect, test, type Page } from '@playwright/test'
import { goTo } from '../nav'
import { seedBusiness } from '../seed'

async function signIn(page: Page, s: { base: string; slug: string; email: string; password: string }) {
  await page.goto('/')
  await page.getByLabel('Server address').fill(s.base)
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByLabel('Business code').fill(s.slug)
  await page.getByLabel('Email').fill(s.email)
  await page.getByLabel('Password').fill(s.password)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('heading', { name: 'Dashboard' })).toBeVisible()
}
const pick = async (page: Page, label: string, text: string, option: RegExp) => { await page.getByLabel(label, { exact: true }).fill(text); await page.getByRole('listbox').getByRole('option', { name: option }).first().click() }

test('manufacturing: set up, make a work order from a bill of materials, see its variance; and send work to a job worker', async ({ page }) => {
  const s = await seedBusiness(process.env['E2E_BACKEND_URL'] as string, process.env['E2E_PLATFORM_TOKEN'] as string, { prefix: 'mfg' })
  await s.call('POST', '/v1/warehouses', { businessLocationId: s.location.id, code: 'JOB', name: 'Job worker site', kind: 'subcontractor' })
  await s.call('POST', '/v1/parties', { code: 'JW-1', legalName: 'Job Works Ltd', gstTreatment: 'unregistered', isSupplier: true, isSubcontractor: true })
  await signIn(page, s)

  // ---- the accounts production posts to ----
  await goTo(page, 'Production costing')
  await page.getByRole('tab', { name: 'Accounts' }).click()
  await pick(page, 'Work in progress', '1230', /1230/)
  await pick(page, 'Labour and machine cost absorbed', '5210', /5210/)
  await pick(page, 'Overhead absorbed', '5230', /5230/)
  await pick(page, 'Production variance', '5260', /5260/)
  await pick(page, 'Job-work charges', '5240', /5240/)
  await page.getByRole('button', { name: 'Save accounts' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Production accounts saved' })).toBeVisible()

  // ---- a work centre ----
  await goTo(page, 'Work centres')
  await page.getByRole('button', { name: 'New work centre' }).click()
  const wc = page.getByRole('dialog', { name: 'New work centre' })
  await wc.getByLabel('Code').fill('ASM'); await wc.getByLabel('Name').fill('Assembly')
  await wc.getByLabel('Labour rate per hour').fill('200'); await wc.getByLabel('Machine rate per hour').fill('100'); await wc.getByLabel('Overhead rate per hour').fill('50')
  await wc.getByRole('button', { name: 'Create' }).click()
  await expect(page.getByRole('cell', { name: 'Assembly' })).toBeVisible()

  // ---- a bill of materials: a widget is made of 2 toys (5% scrap) and one assembly operation ----
  await goTo(page, 'Bills of material')
  await page.getByRole('button', { name: 'New bill of materials' }).click()
  const bom = page.getByRole('dialog', { name: 'New bill of materials' })
  await bom.getByLabel('Finished item', { exact: true }).fill('wid'); await bom.getByRole('option', { name: /WIDGET/ }).click()
  await bom.getByLabel('Component', { exact: true }).fill('toy'); await bom.getByRole('option', { name: /TOY/ }).click()
  await bom.getByLabel('Quantity', { exact: true }).fill('2'); await bom.getByLabel('Scrap percent').fill('5')
  await bom.getByRole('button', { name: '+ Add operation' }).click()
  await bom.getByLabel('Operation 10').fill('Assemble'); await bom.getByLabel('Setup hrs').fill('0.5'); await bom.getByLabel('Run hrs').fill('1')
  await bom.getByRole('button', { name: 'Create bill of materials' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'BOM/' })).toBeVisible()
  await page.getByRole('cell', { name: /BOM\// }).click()
  await expect(page.getByRole('table', { name: 'Components' })).toContainText('TOY')
  await expect(page.getByLabel('Cost roll-up')).toContainText('Total')
  await page.keyboard.press('Escape')

  // ---- a work order: release, issue, report time and output, complete ----
  await goTo(page, 'Work orders')
  await page.getByRole('button', { name: 'New work order' }).click()
  const wo = page.getByRole('dialog', { name: 'New work order' })
  await wo.getByLabel('Item to make', { exact: true }).fill('wid'); await wo.getByRole('option', { name: /WIDGET/ }).click()
  await wo.getByLabel('Quantity', { exact: true }).fill('10')
  await wo.getByRole('button', { name: 'Create work order' }).click()
  await expect(page.getByRole('heading', { name: /^WO\// })).toBeVisible()
  await page.getByRole('button', { name: 'Release' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'released' })).toBeVisible()
  await page.getByRole('button', { name: 'Issue materials' }).click()
  await page.getByRole('dialog', { name: 'Issue materials' }).getByRole('button', { name: 'Issue materials' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Issue materials: done' })).toBeVisible()
  await expect(page.getByRole('table', { name: 'Work order materials' })).toContainText('21.052632')
  await page.getByRole('button', { name: 'Report time' }).click()
  await page.getByLabel('Hours for Assemble').fill('10')
  await page.getByRole('dialog', { name: 'Report time' }).getByRole('button', { name: 'Report time' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Report time: done' })).toBeVisible()
  await page.getByRole('button', { name: 'Report output' }).click()
  const out = page.getByRole('dialog', { name: 'Report output' })
  await out.getByLabel('Good units made').fill('10'); await out.getByLabel('Spoiled units').fill('1')
  await out.getByRole('button', { name: 'Report output' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Report output: done' })).toBeVisible()
  await page.getByRole('button', { name: 'Complete', exact: true }).click()
  await page.getByRole('dialog', { name: 'Complete work order' }).getByRole('button', { name: 'Complete work order' }).click()
  await expect(page.getByText('Completed ·')).toBeVisible()
  await expect(page.getByLabel('Work order cost')).toContainText('11,921.05')
  await expect(page.getByRole('table', { name: 'Variance' })).toContainText('Total')

  // ---- costing reports ----
  await goTo(page, 'Production costing')
  await expect(page.getByRole('table', { name: 'Variances' })).toContainText('WO/')
  await page.getByRole('tab', { name: 'Work in progress' }).click()
  await expect(page.getByText('The books agree with the open work orders.')).toBeVisible()

  // ---- job work ----
  await goTo(page, 'Job work')
  await page.getByRole('button', { name: 'New job-work order' }).click()
  const jw = page.getByRole('dialog', { name: 'New job-work order' })
  await jw.getByLabel('Job worker', { exact: true }).fill('Job'); await jw.getByRole('option', { name: /Job Works/ }).click()
  await jw.getByLabel('Item to be made', { exact: true }).fill('wid'); await jw.getByRole('option', { name: /WIDGET/ }).click()
  await jw.getByLabel('Quantity', { exact: true }).fill('4'); await jw.getByLabel('Charge per unit').fill('30')
  await jw.getByRole('button', { name: 'Create order' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'created for the job worker' })).toBeVisible()
  await page.getByRole('row', { name: /Job Works Ltd/ }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Release' }).click()
  await page.getByRole('button', { name: 'Send materials' }).click()
  await page.getByRole('dialog', { name: /Send materials/ }).getByRole('button', { name: /Send materials/ }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Materials sent' })).toBeVisible()
  await page.getByRole('button', { name: 'Receive goods' }).click()
  await page.getByLabel('Good units received').fill('4')
  await page.getByRole('dialog', { name: 'Receive finished goods' }).getByRole('button', { name: 'Receive finished goods' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Goods received' })).toBeVisible()
  await expect(page.getByLabel('Job work cost')).toContainText('120.00')
})
