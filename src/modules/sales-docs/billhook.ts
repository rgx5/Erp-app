import { audit, OpError } from '@/data/ops'
import { listOf, type Changes, type DataState } from '@/data/state'
import { id } from '@/domain/ids'
import { round2 } from '@/domain/money'
import type { Bill } from '@/domain/types'
import type { BillHook, BillHookCtx } from '@/modules/registry'
import { advanceSource, isOpenOrder, moneyOf } from './logic/orders'
import type { OrderPayment } from './types'

/** The key a module's data lives under in `bill.ext`. */
export const EXT = 'sales-docs'

export interface BillLink {
  /** Billed from this quotation. */
  quotationId?: string
  /** Billed from (fulfilling) this sales order. */
  orderId?: string
  /** An invoice generated by this plan, for this period. */
  subscriptionId?: string
  period?: number
}

export const linkOf = (b: Pick<Bill, 'ext'>): BillLink => ((b.ext?.[EXT] as BillLink | undefined) ?? {})
const advanceTotal = (b: Pick<Bill, 'payments'>) => round2(b.payments.filter((p) => p.mode === 'advance').reduce((s, p) => s + p.amount, 0))

/** Refuses a bill that cannot honour what it says: an advance nobody holds, a quotation already billed, an order already closed. */
function beforeSave({ state, bill }: BillHookCtx) {
  const link = linkOf(bill)
  if (link.quotationId) {
    const q = state.quotations[link.quotationId]
    if (!q) throw new OpError('The quotation for this bill no longer exists.')
    if (q.status === 'converted') throw new OpError(`${q.no} has already been billed.`)
  }
  if (link.orderId) {
    const o = state.salesOrders[link.orderId]
    if (!o) throw new OpError('The order for this bill no longer exists.')
    if (!isOpenOrder(o)) throw new OpError(`${o.no} is already ${o.status}.`)
  }
  const adv = advanceTotal(bill)
  if (adv > 0) {
    const src = advanceSource(state, bill.customerId, link.orderId)
    if (!src) throw new OpError('No advance is held for this customer.')
    if (adv > src.onHand + 0.005) throw new OpError(`Only ₹${src.onHand} of advance is held for this customer.`)
  }
}

/** Writes what the bill means for quotations, orders and challans, in the same transaction as the bill. */
function onSave({ state, ctx, bill }: BillHookCtx): Changes | null {
  const link = linkOf(bill)
  const out: Changes = {}
  const logs: Array<ReturnType<typeof audit>> = []
  const put: Record<string, unknown[]> = {}
  const add = (coll: string, doc: unknown) => { (put[coll] ??= []).push(doc) }

  if (link.quotationId && state.quotations[link.quotationId]) {
    const q = state.quotations[link.quotationId]
    add('quotations', { ...q, status: 'converted', billId: bill.id, convertedAt: ctx.now })
    logs.push(audit(ctx, 'QUOTE_BILLED', `${q.no} → ${bill.no}`))
  }

  const adv = advanceTotal(bill)
  if (adv > 0) {
    const src = advanceSource(state, bill.customerId, link.orderId)
    if (src) {
      const applied: OrderPayment = {
        id: id('opy', ctx.now), orderId: src.order.id, customerId: src.order.customerId, date: ctx.now, kind: 'applied', amount: adv, mode: 'advance', ref: bill.no, note: '',
        billId: bill.id, userId: ctx.userId, ...(ctx.branchId ? { branchId: ctx.branchId } : {}),
      }
      add('orderPayments', applied)
      logs.push(audit(ctx, 'ORDER_ADVANCE_USED', `${src.order.no} — ₹${adv} on ${bill.no}`))
    }
  }

  if (link.orderId && state.salesOrders[link.orderId]) {
    const o = state.salesOrders[link.orderId]
    add('salesOrders', { ...o, status: 'delivered', billId: bill.id })
    for (const c of listOf(state.challans)) if (c.orderId === o.id && !c.billId) add('challans', { ...c, billId: bill.id })
    logs.push(audit(ctx, 'ORDER_DELIVERED', `${o.no} → ${bill.no}`))
  }

  if (!Object.keys(put).length) return null
  out.put = { ...(put as Changes['put']), audit: logs }
  return out
}

export const salesDocsBillHook: BillHook = { id: EXT, beforeSave, onSave }

/** What this module prints on a bill: where it came from, and any advance used. */
export function receiptHeader(bill: Bill, state: DataState): string[] {
  const link = linkOf(bill)
  const out: string[] = []
  if (link.quotationId && state.quotations[link.quotationId]) out.push(`Against quotation ${state.quotations[link.quotationId].no}`)
  if (link.orderId && state.salesOrders[link.orderId]) out.push(`Against order ${state.salesOrders[link.orderId].no}`)
  return out
}
export function receiptFooter(bill: Bill): string[] {
  const adv = advanceTotal(bill)
  return adv > 0 ? [`Advance adjusted: ₹${adv}`] : []
}

export { moneyOf }
